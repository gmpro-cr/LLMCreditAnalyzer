def _ollama_call(prompt: str) -> str:
    url   = os.getenv("OLLAMA_URL", "http://localhost:11434")
    model = os.getenv("OLLAMA_MODEL", "qwen3:8b")
    system = (
        "/no_think\n"
        "You are a senior credit risk analyst at an Indian commercial bank. "
        "Write formal, concise, banker-grade credit appraisal sections. "
        "Use ONLY the data provided. Do NOT fabricate figures. "
        "Output ONLY the requested section text in plain prose (no extra headings)."
    )
    try:
        body: dict = {
            "model": model,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.3,
            "stream": False,
            "think": False,          # disable extended thinking for qwen3 and similar models
            "options": {"num_predict": 1024},  # cap output tokens to avoid runaway generation
        }
        resp = httpx.post(
            f"{url}/v1/chat/completions",
            json=body,
            timeout=60.0,            # 60s per section; fall back to Gemini if Ollama is busy/slow
        )
        resp.raise_for_status()
        text = resp.json()["choices"][0]["message"]["content"].strip()
        # Strip any residual think blocks the model may emit anyway
        return re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()
    except Exception as e:
        logger.error(f"Ollama call error: {e}")
        return ""




# Tried in order. flash-lite returns 503 "high demand" at peak; the full flash
# model is a separate capacity pool on the same key, so it's a free fallback.
GEMINI_MODELS = [m.strip() for m in os.getenv(
    "GEMINI_MODELS", "models/gemini-flash-lite-latest,models/gemini-flash-latest").split(",") if m.strip()]


def _gemini_call(prompt: str) -> str:
    try:
        from google import genai
        from google.genai import types
    except Exception as e:
        logger.error(f"google-genai unavailable: {e}")
        return ""
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        return ""
    # A fresh client per call: a shared client ended up closed after a timed-out
    # request, and every later call failed with "client has been closed" until
    # the engine restarted (2026-10-11). Construction is cheap.
    #   timeout — the SDK default is none; one stalled request froze the memo.
    #   retry   — brief backoff on 429/5xx before trying the next model.
    http_options = types.HttpOptions(
        timeout=45_000,
        retry_options=types.HttpRetryOptions(
            attempts=2, initial_delay=2.0, max_delay=6.0, http_status_codes=[429, 500, 502, 503, 504]),
    )
    for model in GEMINI_MODELS:
        try:
            client = genai.Client(api_key=api_key, http_options=http_options)
            response = client.models.generate_content(model=model, contents=prompt)
            text = (response.text or "").strip()
            if text:
                return text
        except Exception as e:
            logger.error(f"Gemini call error ({model}): {e}")
    return ""


def _claude_call(prompt: str) -> str:
    """Call Claude via the `claude` CLI (uses Claude Code Pro subscription — no API key needed)."""
    import subprocess
    system = (
        "You are a senior credit risk analyst at an Indian commercial bank. "
        "Write formal, concise, banker-grade credit appraisal sections. "
        "Use ONLY the data provided. Do NOT fabricate figures. "
        "Output ONLY the requested section text in plain prose (no extra headings)."
    )
    full_prompt = f"{system}\n\n{prompt}"
    # The CLI authenticates via the Claude subscription login. A stale
    # ANTHROPIC_API_KEY in the service env overrides that and breaks the call,
    # so drop it from the child environment.
    env = {k: v for k, v in os.environ.items() if k != "ANTHROPIC_API_KEY"}
    try:
        result = subprocess.run(
            ["claude", "-p", full_prompt],
            capture_output=True,
            text=True,
            timeout=300,
            env=env,
        )
        if result.returncode != 0:
            logger.error(
                f"Claude CLI error (exit {result.returncode}): "
                f"stderr={result.stderr[:500]!r} stdout={result.stdout[:500]!r}"
            )
            return ""
        return result.stdout.strip()
    except Exception as e:
        logger.error(f"Claude CLI call error: {e}")
        return ""


def _llm(prompt: str) -> str:
    provider = os.getenv("MEMO_PROVIDER", "openrouter").lower()
    if provider == "ollama":
        result = _ollama_call(prompt)
        if result:
            return result
        logger.warning("Ollama failed, falling back to Gemini")
        return _gemini_call(prompt)
    elif provider == "openrouter":
        result = _openrouter_call(prompt)
        if result:
            return result
        logger.warning("OpenRouter failed, falling back to Ollama")
        return _ollama_call(prompt)
    elif provider == "groq":
        result = _groq_call(prompt)
        if result:
            return result
        logger.warning("Groq failed, falling back to Ollama")
        return _ollama_call(prompt)
    elif provider == "claude":
        result = _claude_call(prompt)
        if result:
            return result
        logger.warning("Claude CLI unavailable, falling back to Ollama")
        return _ollama_call(prompt)
    elif provider == "gemini":
        result = _gemini_call(prompt)
        if result:
            return result
        # Gemini quota/outage → fall back to Groq's free tier (if GROQ_API_KEY
        # is set), then Ollama as a last resort for local dev.
        logger.warning("Gemini failed, falling back to Groq")
        result = _groq_call(prompt)
        if result:
            return result
        logger.warning("Groq failed, falling back to Ollama")
        return _ollama_call(prompt)
    # Unknown provider — try Ollama then Gemini
    result = _ollama_call(prompt)
    return result if result else _gemini_call(prompt)


