def _resolve_confidence(section_key: str, financials: Dict) -> tuple:
    confidence, reason = SECTION_CONFIDENCE.get(section_key, ("medium", "AI-generated content"))
    if section_key == "company_background":
        ci = financials.get("company_info", {})
        if not ci.get("name") and not ci.get("description"):
            return ("medium", "Company info sparse — verify background details")
    return (confidence, reason)


_CONTEXT_ROWS = {"DSCR (pro forma": "dscr", "Interest Coverage": "interest_coverage",
                 "Debt / Equity": "debt_equity", "EBITDA Margin": "ebitda_margin"}


def _reported_alternates(financials: Dict, ratios: Dict, context_text: str = "") -> Dict[str, list]:
    """Values a memo may legitimately cite for a ratio besides the latest
    computed one: earlier years' figures and Screener's own (often multi-year)
    numbers. Without these the audit flagged D/E 0.56 — FY2024's correct value."""
    pl = financials.get("profit_loss", {}) or {}
    bs = financials.get("balance_sheet", {}) or {}
    sr = financials.get("key_ratios_from_screener", {}) or {}
    alt: Dict[str, list] = {k: [] for k in ("debt_equity", "interest_coverage", "roe", "roce", "dscr",
                                           "ebitda_margin", "net_margin")}
    def series(x):
        return [v for v in (x if isinstance(x, list) else []) if isinstance(v, (int, float))]
    debt, eq = series(bs.get("borrowings")), series(bs.get("total_equity"))
    alt["debt_equity"] += [round(d / e, 2) for d, e in zip(debt, eq) if e]
    eb, it, rv, pt = series(pl.get("ebitda")), series(pl.get("interest")), series(pl.get("revenue")), series(pl.get("pat"))
    alt["interest_coverage"] += [round(a / b, 2) for a, b in zip(eb, it) if b]
    alt["ebitda_margin"] += [round(a / b * 100, 2) for a, b in zip(eb, rv) if b]
    alt["net_margin"] += [round(a / b * 100, 2) for a, b in zip(pt, rv) if b]
    for key, src in (("roe", "roe_pct"), ("roce", "roce_pct"), ("debt_equity", "debt_equity_ratio"),
                     ("interest_coverage", "interest_coverage")):
        if isinstance(sr.get(src), (int, float)):
            alt[key].append(sr[src])
    alt["roce"] += [r.get("roce") for r in sr.get("roce_series") or [] if isinstance(r.get("roce"), (int, float))]
    # Screener "key points", e.g. "low return on equity of 13.3% over last 3 years".
    for kp in (financials.get("company_info", {}) or {}).get("key_points") or []:
        m = re.search(r"return on equity of ([\d.]+)", str(kp), re.I)
        if m:
            alt["roe"].append(float(m.group(1)))
    # Every figure the CMA / projection / stress rows gave the model (e.g. the
    # projected DSCR 1.76x was flagged against the latest-year 1.39x).
    for line in (context_text or "").splitlines():
        for prefix, key in _CONTEXT_ROWS.items():
            if line.startswith(prefix):
                alt[key] += [float(x) for x in re.findall(r"(?<![\w.])\d+\.\d+", line[28:])]
        if line.startswith("STRESS TEST"):
            alt["dscr"] += [float(x) for x in re.findall(r"(\d+\.\d+)x", line)]
    return alt


# ── Public entry point ────────────────────────────────────────────────────────

_WC_TYPES = ("working_capital", "cash_credit", "overdraft", "wc", "cc", "od")


def _strip_dp_table(content: str) -> str:
    """Drop any markdown table mentioning Drawing Power. A DP table only applies
    to WC limits; the model kept emitting a blank one under a Term Loan right
    after writing that it was not applicable."""
    blocks = re.split(r"(\n\s*\n)", content)
    kept = [b for b in blocks
            if not (b.lstrip().startswith("|") and re.search(r"drawing power|working capital gap", b, re.I))]
    return re.sub(r"\n{3,}", "\n\n", "".join(kept)).strip()


def _with_peer_table(content: str, financials: Dict) -> str:
    """Prepend the deterministic peer table; never let the LLM supply peer figures."""
    from cam_tables import peer_table
    table = peer_table(financials)
    if not table:
        return ("_Peer data not available — fetch financials for a listed borrower or add "
                "listed peers in the Data Room._\n\n" + content)
    return table + "\n\n_Source: Screener.in peer comparison (latest reported quarter)._\n\n" + content


def _with_tables(content: str, financials: Dict, ratios: Dict) -> str:
    """Append the deterministic spread + ratio-covenant tables to a section's prose."""
    from cam_tables import financial_spread, ratio_covenant_table
    spread = financial_spread(financials)
    rtable = ratio_covenant_table(ratios)
    extra = []
    if spread:
        extra.append("\n\n**Financial Spread (₹ Cr)**\n\n" + spread)
    if rtable:
        extra.append("\n\n**Key Ratios vs Covenants**\n\n" + rtable)
    if extra:
        extra.append("\n\n_Source: Screener.in / company filings — confirm basis "
                     "(standalone vs consolidated) and verify against audited statements._")
    return content + "".join(extra)


def generate_cam_sections(
    financials: Dict,
    ratios: Dict,
    company_name: str,
    research_brief: str = "",
    regenerate: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Generate AI-drafted CAM sections.

    Args:
        financials: Extracted financial data
        ratios: Computed ratios
        company_name: Borrower name
        research_brief: Optional research brief text
        regenerate: If set, generate only this specific section key

    Returns:
        Dict with section keys → {"content": str, "user_edited": False, "ai_generated": True}
    """
    # For local Ollama, cap context to avoid timeouts
    provider = os.getenv("MEMO_PROVIDER", "openrouter").lower()
    text_limit = int(os.getenv("OLLAMA_TEXT_LIMIT", "8000")) if provider == "ollama" else 0
    context_text = _build_context_text(financials, ratios, company_name, research_brief, max_chars=text_limit)

    if regenerate and regenerate in AI_SECTIONS:
        content = _draft_section(regenerate, context_text, company_name)
        if regenerate == "financial_analysis":
            content = _with_tables(content, financials, ratios)
        elif regenerate == "peer_comparison":
            content = _with_peer_table(content, financials)
        conf, reason = _resolve_confidence(regenerate, financials)
        return {
            regenerate: {
                "content":           content,
                "user_edited":       False,
                "ai_generated":      True,
                "confidence":        conf,
                "confidence_reason": reason,
                "reviewed":          False,
                "low_verified":      False,
                "locked":            False,
            }
        }

    sections: Dict[str, Any] = {}
    # Sections to generate (exclude executive_summary — generated last)
    gen_sections = [k for k in AI_SECTIONS if k != "executive_summary"]

    # Batch generation works well for cloud LLMs; for local Ollama generate individually
    # to avoid context overflow and timeouts.
    use_batch = provider not in ("ollama",)
    batch: Dict[str, str] = {}
    if use_batch:
        # Output tokens generate sequentially within one call, so one giant
        # batch's wall time scales with total output. Small groups drafted in
        # parallel make wall time ≈ the slowest group instead of the sum.
        group_size = 4
        groups = [gen_sections[i:i + group_size] for i in range(0, len(gen_sections), group_size)]
        logger.info(
            f"[CAM] Drafting {len(gen_sections)} sections in {len(groups)} parallel batches for {company_name}"
        )
        with ThreadPoolExecutor(max_workers=len(groups)) as pool:
            futures = [
                pool.submit(_draft_all_sections_batch, context_text, company_name, g)
                for g in groups
            ]
            for fut in as_completed(futures):
                try:
                    batch.update(fut.result() or {})
                except Exception as e:
                    logger.error(f"[CAM] Batch group failed: {e}")

    # Re-draft anything the batch missed — in parallel for cloud providers,
    # sequentially for local Ollama (a local model gains nothing from threads).
    missing = [k for k in gen_sections if not batch.get(k)]
    if missing:
        logger.info(f"[CAM] Generating {len(missing)} sections individually for {company_name}: {missing}")
        if use_batch:
            with ThreadPoolExecutor(max_workers=min(4, len(missing))) as pool:
                batch.update(
                    dict(pool.map(lambda k: (k, _draft_section(k, context_text, company_name)), missing))
                )
        else:
            for k in missing:
                batch[k] = _draft_section(k, context_text, company_name)

    for key in gen_sections:
        content = batch.get(key, "")
        conf, reason = _resolve_confidence(key, financials)
        sections[key] = {
            "content":           content,
            "user_edited":       False,
            "ai_generated":      True,
            "confidence":        conf,
            "confidence_reason": reason,
            "reviewed":          False,
            "low_verified":      False,
            "locked":            False,
        }

    fac_type = str((financials.get("facility") or {}).get("type") or "").lower()
    if "proposed_structure" in sections and fac_type not in _WC_TYPES:
        sections["proposed_structure"]["content"] = _strip_dp_table(sections["proposed_structure"]["content"])

    if "peer_comparison" in sections:
        sections["peer_comparison"]["content"] = _with_peer_table(
            sections["peer_comparison"]["content"], financials
        )

    # Append computed tables to Financial Analysis (math owned by Python, not the LLM)
    if "financial_analysis" in sections:
        sections["financial_analysis"]["content"] = _with_tables(
            sections["financial_analysis"]["content"], financials, ratios
        )

    # Generate executive_summary last — synthesises the other sections
    summary_snippets = []
    for key in ["company_background", "business_model", "financial_analysis", "key_issues", "recommendation"]:
        sec = sections.get(key, {})
        snippet = sec.get("content", "")
        if snippet:
            summary_snippets.append(f"[{key.upper()}]\n{snippet[:400]}")
    exec_extra = ("\n\n--- SECTION SUMMARIES ---\n" + "\n\n".join(summary_snippets)) if summary_snippets else ""
    # Keep exec summary context shorter for Ollama
    exec_context_limit = text_limit if text_limit else 0
    exec_base = _build_context_text(financials, ratios, company_name, research_brief, max_chars=4000 if text_limit else 0)
    exec_context = exec_base + exec_extra
    if exec_context_limit and len(exec_context) > exec_context_limit:
        exec_context = exec_context[:exec_context_limit]
    exec_content = _draft_section("executive_summary", exec_context, company_name)
    conf, reason = _resolve_confidence("executive_summary", financials)
    sections["executive_summary"] = {
        "content":           exec_content,
        "user_edited":       False,
        "ai_generated":      True,
        "confidence":        conf,
        "confidence_reason": reason,
        "reviewed":          False,
        "low_verified":      False,
        "locked":            False,
    }

    # Management PEP fields supplement
    if "management_profile" in sections:
        sections["management_profile"]["pep_checked"] = False
        sections["management_profile"]["pep_notes"]   = ""

    # Deterministic internal rating — prepend to Financial Analysis (math owned
    # by Python, not the LLM).
    try:
        scorecard = compute_scorecard(financials, ratios)
        sc_md = format_scorecard_md(scorecard)
        if sc_md and "financial_analysis" in sections:
            sections["financial_analysis"]["content"] = (
                sc_md + "\n\n" + sections["financial_analysis"].get("content", "")
            )
        # expose the structured rating too (engine consumers / UI can use it)
        sections["_credit_rating"] = scorecard
    except Exception as e:
        logger.warning(f"[CAM] Scorecard computation failed: {e}")

    # Number grounding — flag any ratio the LLM cited that disagrees with the
    # computed value, appended to Key Issues.
    try:
        combined = "\n".join(
            s.get("content", "") for s in sections.values() if isinstance(s, dict)
        )
        mismatches = audit_memo_figures(combined, ratios, _reported_alternates(financials, ratios, context_text))
        if mismatches and "key_issues" in sections:
            lines = ["", "", "**Figure Verification (automated):**", ""]
            for m in mismatches:
                lines.append(f"- {m['label'].upper()}: memo states {m['stated']}, "
                             f"computed {m['computed']} — reconcile before reliance.")
            sections["key_issues"]["content"] = (
                sections["key_issues"].get("content", "") + "\n".join(lines)
            )
            sections["_figure_mismatches"] = mismatches
    except Exception as e:
        logger.warning(f"[CAM] Figure audit failed: {e}")

    # Facility-scale check: the model must not restate the loan at a different
    # scale. Strip mis-copied rupee parentheticals; flag over-sized amounts in place.
    fac = financials.get("facility") or {}
    facility_cr = (float(fac["amount_inr"]) / 1e7) if fac.get("amount_inr") else 0.0
    for key, sec in sections.items():
        if not (isinstance(sec, dict) and sec.get("ai_generated") and sec.get("content")):
            continue
        sec["content"] = strip_rupee_restatements(sec["content"])
        issues = audit_facility_amounts(sec["content"], facility_cr)
        if issues:
            amounts = ", ".join(f"₹{i['stated_cr']:,.2f} Cr" for i in issues)
            sec["content"] += (
                f"\n\n**Automated check:** this section cites {amounts} in connection with the "
                f"facility, but the proposed facility is ₹{facility_cr:,.2f} Cr. Correct before reliance."
            )
            sec.setdefault("confidence", "low")
            sec["confidence"] = "low"

    # Recommendation-consistency check — flag if the narrative leans "approve"
    # while the deterministic grade/risk flags say otherwise. Reads the grade back
    # from sections["_credit_rating"] rather than a local variable so this is safe
    # even if the scorecard computation above failed.
    try:
        from risk_flags import generate_risk_flags
        flags = generate_risk_flags(ratios, financials)
        # Returned so the API can persist them — previously computed and dropped,
        # leaving the case's Risk Flags panel permanently at 0.
        sections["_risk_flags"] = flags
        scorecard = sections.get("_credit_rating", {})
        rec_content = sections.get("recommendation", {}).get("content", "")
        rec_issues = audit_recommendation_consistency(rec_content, scorecard, flags)
        if rec_issues and "recommendation" in sections:
            lines = ["", "", "**Recommendation Consistency Check (automated):**", ""]
            for i in rec_issues:
                lines.append(f"- {i['message']}")
            sections["recommendation"]["content"] += "\n".join(lines)
            sections["_recommendation_conflicts"] = rec_issues
    except Exception as e:
        logger.warning(f"[CAM] Recommendation consistency check failed: {e}")

    # Deterministic scaffolds — never LLM-narrated. Nothing here is knowable from
    # financial statements at appraisal time (EWS trigger status depends on live
    # post-sanction account conduct; reference checks are a human due-diligence
    # task), so these are static templates for the RM to complete, not generated
    # content that could hallucinate company-specific claims.
    ews_conf, ews_reason = SECTION_CONFIDENCE["ews_checklist"]
    sections["ews_checklist"] = {
        "content":           format_ews_checklist_md(),
        "user_edited":       False,
        "ai_generated":      False,
        "confidence":        ews_conf,
        "confidence_reason": ews_reason,
        "reviewed":          False,
        "low_verified":      False,
        "locked":            False,
    }
    ref_conf, ref_reason = SECTION_CONFIDENCE["reference_check"]
    sections["reference_check"] = {
        "content": (
            "## Reference Check\n\n"
            "_To be completed by the RM as part of due diligence._\n\n"
            "| Counterparty | Relationship | Contact Person | Date of Check | Key Feedback |\n"
            "|---|---|---|---|---|\n"
            "| | Banker | | | |\n"
            "| | Supplier | | | |\n"
            "| | Customer | | | |\n"
        ),
        "user_edited":       False,
        "ai_generated":      False,
        "confidence":        ref_conf,
        "confidence_reason": ref_reason,
        "reviewed":          False,
        "low_verified":      False,
        "locked":            False,
    }

    return sections
