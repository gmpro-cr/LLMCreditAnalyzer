# ── Batch generation via a single LLM call ───────────────────────────────────

def _draft_all_sections_batch(
    context_text: str,
    company_name: str,
    sections: list = None,
) -> Dict[str, str]:
    """
    One LLM call to generate all AI sections separated by delimiters.
    Fallback: generate each section individually.
    """
    target = sections if sections is not None else AI_SECTIONS
    section_list = "\n".join(
        f"{_DELIM}{k}###\n{SECTION_PROMPTS[k]}"
        for k in target if k in SECTION_PROMPTS
    )
    prompt = f"""{context_text}

---
You are writing a Credit Appraisal Memorandum for "{company_name}".
Generate ALL sections below. Each section must start with its delimiter exactly as shown.

{section_list}

RULES:
- Use ONLY the data provided above. Do NOT fabricate any figures, ratings, customers or events.
- Statements in the WEB RESEARCH BRIEF tagged '(from LLM knowledge — verify)' are UNVERIFIED recall: never use them for assurances (no defaults, no restructuring, no litigation, no governance issues, no pledge) or for ratings; any other fact from them must carry '(to be verified)'.
- Amounts: Indian digit grouping, whole crores for amounts of ₹100 Cr or more (₹8,969 Cr, ₹1,63,062 Cr),
  two decimals below that (₹50.00 Cr). Ratios to two decimals with an x (1.39x).
- Each section: 2-4 paragraphs of formal banker prose.
- Do NOT add extra headings inside sections.
- Do NOT output any <think> tags.
- Start the first section immediately after its delimiter.
"""
    raw = _llm(prompt)
    if not raw:
        return {}
    return _parse_sections(raw)


def _parse_sections(raw: str) -> Dict[str, str]:
    result: Dict[str, str] = {}
    # Split on ###SECTION:key###
    parts = re.split(r"###SECTION:(\w+)###", raw)
    i = 1
    while i + 1 <= len(parts):
        key  = parts[i].strip()
        body = parts[i + 1].strip() if i + 1 < len(parts) else ""
        if key in AI_SECTIONS and body:
            result[key] = body
        i += 2
    return result


